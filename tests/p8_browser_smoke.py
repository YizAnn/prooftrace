from playwright.sync_api import sync_playwright
from pathlib import Path
import json,time,html
out=Path(__file__).resolve().parents[1]/'preview';out.mkdir(exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage','--no-proxy-server','--proxy-bypass-list=*'])
 page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
 errors=[]; logs=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.on('console',lambda c:logs.append((c.type,c.text)) if c.type=='error' else None)
 root=Path(__file__).resolve().parents[1]
 markup=(root/'index.html').read_text()
 registry=(root/'data/beijing_registry.js').read_text()
 home=(root/'home.html').read_text()
 markup=markup.replace('<script src="data/beijing_registry.js"></script>','<script>'+registry+'</script>')
 markup=markup.replace('src="home.html"','srcdoc="'+html.escape(home,quote=True)+'"')
 page.set_content(markup,wait_until='domcontentloaded',timeout=30000)
 page.locator('iframe#p8-home-frame').content_frame.locator('.hero h1').wait_for(timeout=25000)
 page.wait_for_timeout(500)
 print('LANDING heading',page.frame_locator('#p8-home-frame').locator('h1').first.inner_text())
 page.screenshot(path=str(out/'P8_home_1440.png'))
 page.frame_locator('#p8-home-frame').locator('.hero-actions button.open-work').click()
 page.wait_for_timeout(1100)
 print('AFTER CLICK view',page.locator('body').get_attribute('data-view'),'app hidden',page.locator('#app').get_attribute('hidden'))
 page.screenshot(path=str(out/'P8_research_1440.png'))
 print('Research title',page.locator('.p8-stage h1').first.inner_text())
 print('P8 AI prompt',page.locator('#p8-ask-text').count())
 page.evaluate("setView('evidence')")
 page.wait_for_timeout(850)
 print('EVIDENCE view',page.locator('body').get_attribute('data-view'),'nodes',page.locator('[data-p8-ev]').count())
 page.screenshot(path=str(out/'P8_evidence_graph_1440.png'))
 page.locator('[data-p8-ev]').nth(2).click()
 page.wait_for_timeout(160)
 print('Selected',page.locator('#p8-graph-detail small').inner_text())
 page.locator('[data-p8="open-evidence"]').click()
 page.wait_for_timeout(450)
 print('EVIDENCE LIST',page.locator('#ev-list .evitem').count(),'visible?',page.locator('#p8-original-evidence').get_attribute('data-hidden'))
 page.screenshot(path=str(out/'P8_evidence_review_1440.png'))
 page.evaluate("setView('model')")
 page.wait_for_timeout(600)
 print('MODEL',page.locator('.p8-tmetric').count(),'body view',page.locator('body').get_attribute('data-view'))
 page.screenshot(path=str(out/'P8_evaluation_1440.png'))
 page.evaluate("setView('rules')")
 page.wait_for_timeout(450)
 print('RULES view',page.locator('body').get_attribute('data-view'),'rule editor elements',page.locator('[data-action="rule-edit"]').count())
 page.evaluate("setView('registry')")
 page.wait_for_timeout(550)
 print('REGISTRY view',page.locator('body').get_attribute('data-view'))
 page.evaluate("setView('profile')")
 page.wait_for_timeout(500)
 page.locator('#p8-ask-text').fill('请梳理核心技术证据缺口')
 page.locator('[data-p8="ask"]').click()
 page.wait_for_timeout(1200)
 print('AGENT rail visible',page.locator('body').get_attribute('class'),'messages',page.locator('#agent-log').inner_text()[:180])
 page.screenshot(path=str(out/'P8_agent_unconfigured_1440.png'))
 print('ERRORS',errors[:12]);print('console err',logs[:8]);
 (out/'browser_smoke_result.json').write_text(json.dumps({'errors':errors,'logs':logs,'views':['profile','evidence','model','rules','registry'],'nodes':11},ensure_ascii=False,indent=2))
 browser.close()
